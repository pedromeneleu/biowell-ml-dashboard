-- Exporta a ESTRUTURA do schema ml_dashboards (sem dados).
-- Somente leitura: nao cria, altera nem apaga nada.
-- Rode no SQL Editor do Supabase e copie o conteudo da coluna "ddl" (uma celula so).
with
params as (
  select 'ml_dashboards'::text as schema_name
),
ns as (
  select n.oid, n.nspname
  from pg_namespace n, params p
  where n.nspname = p.schema_name
),
-- Views e materialized views em ordem de dependencia (as que dependem de outras vem depois).
view_deps as (
  select distinct v.oid as view_oid, d.refobjid as dep_oid
  from pg_class v
  join ns on ns.oid = v.relnamespace
  join pg_rewrite rw on rw.ev_class = v.oid
  join pg_depend d on d.objid = rw.oid
    and d.classid = 'pg_rewrite'::regclass
    and d.refclassid = 'pg_class'::regclass
  where v.relkind in ('v', 'm') and d.refobjid <> v.oid
),
view_levels as (
  with recursive lvl(oid, depth) as (
    select v.oid, 0
    from pg_class v join ns on ns.oid = v.relnamespace
    where v.relkind in ('v', 'm')
    union all
    select vd.view_oid, lvl.depth + 1
    from view_deps vd join lvl on vd.dep_oid = lvl.oid
    where lvl.depth < 50
  )
  select oid, max(depth) as depth from lvl group by oid
),
parts as (
  -- 1. Sequences avulsas (as de colunas identity sao criadas junto com a tabela)
  select 10 as ordem, 0 as sub, c.relname::text as objeto,
    format('create sequence if not exists %I.%I as %s increment by %s minvalue %s maxvalue %s start with %s%s;',
      ns.nspname, c.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax, s.seqstart,
      case when s.seqcycle then ' cycle' else '' end) as ddl
  from pg_class c
  join ns on ns.oid = c.relnamespace
  join pg_sequence s on s.seqrelid = c.oid
  where c.relkind = 'S'
    and not exists (
      select 1 from pg_depend d
      where d.objid = c.oid and d.classid = 'pg_class'::regclass and d.deptype = 'i'
    )

  union all
  -- 2. Tabelas (colunas, tipos, defaults, not null, identity, colunas geradas)
  select 20, 0, c.relname::text,
    format(E'create table if not exists %I.%I (\n%s\n);', ns.nspname, c.relname,
      string_agg(
        format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case
             when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
             else ''
           end
        || case when a.attnotnull then ' not null' else '' end,
        E',\n' order by a.attnum))
  from pg_class c
  join ns on ns.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
  where c.relkind in ('r', 'p')
  group by ns.nspname, c.relname

  union all
  -- 3. Chaves primarias, unicas, checks e exclusoes
  select 30, case con.contype when 'p' then 0 when 'u' then 1 else 2 end, con.conrelid::regclass::text || '.' || con.conname,
    format('alter table %s add constraint %I %s;', con.conrelid::regclass, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con
  join ns on ns.oid = con.connamespace
  where con.contype in ('p', 'u', 'c', 'x') and con.conrelid <> 0

  union all
  -- 4. Chaves estrangeiras (depois de todas as chaves primarias/unicas)
  select 40, 0, con.conrelid::regclass::text || '.' || con.conname,
    format('alter table %s add constraint %I %s;', con.conrelid::regclass, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con
  join ns on ns.oid = con.connamespace
  where con.contype = 'f'

  union all
  -- 5. Indices que nao pertencem a uma constraint
  select 50, 0, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i
  join pg_class t on t.oid = i.indrelid
  join ns on ns.oid = t.relnamespace
  where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid and con.contype in ('p', 'u', 'x'))

  union all
  -- 6. Funcoes e procedures do schema
  select 60, 0, p.oid::regprocedure::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  join ns on ns.oid = p.pronamespace
  where p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  union all
  -- 7. Views e materialized views (ordem de dependencia)
  select 70, vl.depth, c.relname::text,
    case c.relkind
      when 'v' then format(E'create or replace view %I.%I%s as\n%s', ns.nspname, c.relname,
        case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
        pg_get_viewdef(c.oid, true))
      else format(E'create materialized view if not exists %I.%I as\n%s', ns.nspname, c.relname,
        rtrim(pg_get_viewdef(c.oid, true), ';')) || E'\nwith data;'
    end
  from pg_class c
  join ns on ns.oid = c.relnamespace
  join view_levels vl on vl.oid = c.oid
  where c.relkind in ('v', 'm')

  union all
  -- 8. Triggers
  select 80, 0, tg.tgrelid::regclass::text || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join ns on ns.oid = c.relnamespace
  where not tg.tgisinternal

  union all
  -- 9. RLS ligado
  select 90, 0, c.relname::text, format('alter table %I.%I enable row level security;', ns.nspname, c.relname)
  from pg_class c
  join ns on ns.oid = c.relnamespace
  where c.relkind in ('r', 'p') and c.relrowsecurity

  union all
  -- 10. Policies de RLS
  select 91, 0, pol.tablename || '.' || pol.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;',
      pol.policyname, pol.schemaname, pol.tablename, pol.permissive, pol.cmd, array_to_string(pol.roles, ', '),
      coalesce(' using (' || pol.qual || ')', ''),
      coalesce(' with check (' || pol.with_check || ')', ''))
  from pg_policies pol, params p
  where pol.schemaname = p.schema_name
)
select
  count(*) as objetos,
  E'-- Estrutura de ml_dashboards exportada em ' || now()::text || E'\n\n'
    || string_agg(ddl, E'\n\n' order by ordem, sub, objeto) as ddl
from parts;
